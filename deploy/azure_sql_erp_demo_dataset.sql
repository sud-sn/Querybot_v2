/*
QueryBot ERP Demo Dataset for Azure SQL
======================================

Purpose
-------
Creates a production-style ERP test schema with cryptic naming, multiple date
roles, competing business columns, derived metrics, deleted-record flags, and
join paths that exercise QueryBot's semantic layer, metric registry, entity
graph, date-role handling, and validator.

Run in Azure SQL / SQL Server:
  sqlcmd -S <server> -d <database> -U <user> -P <password> -i deploy/azure_sql_erp_demo_dataset.sql

Schema created:
  EMDW_DMART_DEMO

Important semantic mappings to add/approve in QueryBot after KB generation:
  - Revenue / Sales Amount:
      CUS_ORD_IVC_FCT.SOP_CUS_IVC_LIN_AMT
      Metric expression: SUM(CASE WHEN DEL_IVC_REC_IND = 0 THEN SOP_CUS_IVC_LIN_AMT ELSE 0 END)
  - Cost Amount:
      CUS_ORD_IVC_FCT.SOP_CUS_IVC_LIN_CST_AMT
  - Gross Profit:
      CUS_ORD_IVC_FCT.SOP_CUS_LIN_GRS_PFT_AMT
  - Purchase Order Amount:
      PCH_ORD_RCT_FCT.PCH_ORD_LIN_CAD_AMT
      This intentionally supersedes PCH_ORD_LIN_AMT.
  - Purchase Order Quantity:
      PCH_ORD_RCT_FCT.PCH_ORD_AUM_QTY
      This intentionally supersedes ITM_BAL_PRD_FCT.PCH_QTY.
  - Open Order Quantity:
      SUM(PCH_ORD_AUM_QTY) - SUM(PCH_ORD_RVD_QTY)
  - Rejected Inventory Quantity:
      ITM_BAL_PRD_FCT.RJC_ON_HND_QTY

Date roles:
  - Invoice Date:        CUS_ORD_IVC_FCT.CUS_IVC_DT_DMS_KEY -> DT_DMS.DT_DMS_KEY
  - Customer Order Date: CUS_ORD_IVC_FCT.CUS_ORD_DT_DMS_KEY -> DT_DMS.DT_DMS_KEY
  - Due Date:            CUS_ORD_IVC_FCT.CUS_IVC_DUE_DT_DMS_KEY -> DT_DMS.DT_DMS_KEY
  - Purchase Order Date: PCH_ORD_RCT_FCT.PCH_ORD_DT_DMS_KEY -> DT_DMS.DT_DMS_KEY
  - Receipt Date:        PCH_ORD_RCT_FCT.PCH_RCT_DT_DMS_KEY -> DT_DMS.DT_DMS_KEY
  - Balance Period:      ITM_BAL_PRD_FCT.BAL_PRD_DT_DMS_KEY -> DT_DMS.DT_DMS_KEY
  - Replacement Cost As-of Date: RPL_CST_FCT.RPL_CST_DT_DMS_KEY -> DT_DMS.DT_DMS_KEY
  - Payment Due Date:    FNN_FCT.DUE_DT_DMS_KEY -> DT_DMS.DT_DMS_KEY
  - Payment Date:        FNN_FCT.PAY_DT_DMS_KEY -> DT_DMS.DT_DMS_KEY

This script resets only objects inside EMDW_DMART_DEMO.
*/

