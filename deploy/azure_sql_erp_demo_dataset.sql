WITH dated AS (
    SELECT
        YEAR(d.DMS_DT) AS YR,
        f.SOP_CUS_IVC_LIN_AMT,
        f.DEL_IVC_REC_IND
    FROM EMDW_DMART_DEMO.CUS_ORD_IVC_FCT f
    JOIN EMDW_DMART_DEMO.DT_DMS d ON f.CUS_IVC_DT_DMS_KEY = d.DT_DMS_KEY
),
base AS (
    SELECT YR, SUM(CASE WHEN DEL_IVC_REC_IND = 0 THEN SOP_CUS_IVC_LIN_AMT ELSE 0 END) AS Revenue
    FROM dated
    GROUP BY YR
)
SELECT
    c.YR AS Current_Year,
    c.Revenue AS Current_Revenue,
    p.YR AS Previous_Year,
    p.Revenue AS Previous_Revenue,
    c.Revenue - p.Revenue AS Revenue_Difference,
    ROUND((c.Revenue - p.Revenue) * 100.0 / NULLIF(p.Revenue, 0), 2) AS Revenue_Pct_Change
FROM base c
LEFT JOIN base p ON p.YR = c.YR - 1
WHERE c.YR = (SELECT MAX(YR) FROM base);

