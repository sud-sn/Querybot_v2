SELECT
    CONVERT(int, CONVERT(char(8), dte, 112)),
    dte,
    CONVERT(nvarchar(30), dte, 23),
    YEAR(dte),
    DATEPART(quarter, dte),
    MONTH(dte),
    DATENAME(month, dte),
    FORMAT(dte, 'yyyy-MM'),
    CASE WHEN MONTH(dte) >= 4 THEN YEAR(dte) + 1 ELSE YEAR(dte) END,
    CASE WHEN MONTH(dte) >= 4 THEN MONTH(dte) - 3 ELSE MONTH(dte) + 9 END,
    DATEPART(iso_week, dte),
    CASE WHEN DATENAME(weekday, dte) IN ('Saturday', 'Sunday') THEN 1 ELSE 0 END
FROM d
OPTION (MAXRECURSION 0);

